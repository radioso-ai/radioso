#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const importPattern = /import\s+(?:type\s+)?(?:[\s\S]*?\s+from\s+)?["']([^"']+)["']|export\s+(?:type\s+)?(?:[\s\S]*?\s+from\s+)["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)/g;
const sourceExtensions = new Set([".ts", ".tsx", ".js", ".mjs", ".cjs"]);

const ossSourceRoots = [
  "backend/src",
  "backend/tests",
  "frontend",
  "packages",
  "typescript-sdk",
];

const generatedRouteMarker = "Generated by scripts/sync-ee-frontend-routes.mjs";
const approvedCrossModuleSupportEntrypoints = new Set([
  "backend/src/modules/chat/retrievalSupport",
  "backend/src/modules/documents/historySupport",
]);

export const validateRepositoryBoundaries = async (root = repoRoot) => {
  const records = await collectImportRecords(root);
  const result = validateImportRecords(records, { checkPrivateCrossModuleImports: true });
  return result;
};

export const validateImportRecords = (
  records,
  options = { checkPrivateCrossModuleImports: true },
) => {
  const errors = [];
  for (const record of records) {
    if (isOssSourcePath(record.filePath) && isEnterpriseSpecifier(record.specifier)) {
      errors.push(
        `OSS source must not import Enterprise code: ${record.filePath} -> ${record.specifier}`,
      );
    }

    const conversationContractError = validateConversationContractImport(record);
    if (conversationContractError) {
      errors.push(conversationContractError);
    }

    const conversationEngineError = validateConversationEngineImport(record);
    if (conversationEngineError) {
      errors.push(conversationEngineError);
    }

    const mcpServerError = validateMcpServerImport(record);
    if (mcpServerError) {
      errors.push(mcpServerError);
    }

    const censusError = validateCensusImport(record);
    if (censusError) {
      errors.push(censusError);
    }

    if (options.checkPrivateCrossModuleImports !== false) {
      const crossModuleError = validateCrossModuleImport(record);
      if (crossModuleError) {
        errors.push(crossModuleError);
      }
    }
  }

  return {
    valid: errors.length === 0,
    errors,
  };
};

const validateMcpServerImport = (record) => {
  const filePath = normalizePath(record.filePath);
  if (!filePath.startsWith("packages/radioso-mcp-server/")) {
    return null;
  }
  // The rule guards the SHIPPED MCP server (src/). Test and smoke harnesses legitimately mount the
  // backend in-process to exercise the published HTTP surface, so they may import backend code.
  if (/^packages\/radioso-mcp-server\/(testing|tests|scripts)\//.test(filePath)) {
    return null;
  }

  const resolved = resolveImportPath(record.filePath, record.specifier);
  if (!resolved) {
    return null;
  }

  if (resolved.startsWith("backend/src/")) {
    return `Radioso MCP server must call backend over HTTP instead of importing backend code: ${record.filePath} -> ${record.specifier}`;
  }

  return null;
};

const validateCrossModuleImport = (record) => {
  const sourceMatch = normalizePath(record.filePath).match(/^backend\/src\/modules\/([^/]+)\//);
  if (!sourceMatch) {
    return null;
  }
  const resolved = resolveImportPath(record.filePath, record.specifier);
  if (!resolved) {
    return null;
  }
  const targetMatch = resolved.match(/^backend\/src\/modules\/([^/]+)\//);
  if (!targetMatch || targetMatch[1] === sourceMatch[1]) {
    return null;
  }
  const targetModulePath = resolved.slice(`backend/src/modules/${targetMatch[1]}/`.length);
  if (targetModulePath === "public") {
    return null;
  }
  if (targetModulePath.startsWith("contracts/") || targetModulePath.startsWith("templates/")) {
    return null;
  }
  if (approvedCrossModuleSupportEntrypoints.has(resolved)) {
    return null;
  }
  if (targetModulePath === "composition") {
    return `Backend module composition entrypoints are for application wiring only: ${record.filePath} -> ${record.specifier}`;
  }
  return `Backend modules must use public contracts for cross-module imports: ${record.filePath} -> ${record.specifier}`;
};

const validateConversationContractImport = (record) => {
  const filePath = normalizePath(record.filePath);
  if (!filePath.startsWith("packages/conversation-contract/")) {
    return null;
  }

  if (record.specifier.startsWith("@radioso/")) {
    return `Conversation contract must not import Radioso product implementation code: ${record.filePath} -> ${record.specifier}`;
  }

  const resolved = resolveImportPath(record.filePath, record.specifier);
  if (!resolved) {
    return null;
  }

  if (resolved.startsWith("packages/conversation-contract/")) {
    return null;
  }

  if (
    resolved.startsWith("backend/") ||
    resolved.startsWith("frontend/") ||
    resolved.startsWith("docs-portal/") ||
    resolved.startsWith("typescript-sdk/") ||
    resolved.startsWith("ee/") ||
    resolved.startsWith("packages/")
  ) {
    return `Conversation contract must not import Radioso product implementation code: ${record.filePath} -> ${record.specifier}`;
  }

  return null;
};

const validateConversationEngineImport = (record) => {
  const filePath = normalizePath(record.filePath);
  if (!filePath.startsWith("packages/conversation-engine/")) {
    return null;
  }

  if (record.specifier === "@radioso/conversation-contract") {
    return null;
  }

  if (record.specifier.startsWith("@radioso/")) {
    return `Conversation engine must not import Radioso product implementation code: ${record.filePath} -> ${record.specifier}`;
  }

  const resolved = resolveImportPath(record.filePath, record.specifier);
  if (!resolved) {
    return null;
  }

  if (resolved.startsWith("packages/conversation-engine/")) {
    return null;
  }

  if (
    resolved.startsWith("backend/") ||
    resolved.startsWith("frontend/") ||
    resolved.startsWith("docs-portal/") ||
    resolved.startsWith("typescript-sdk/") ||
    resolved.startsWith("ee/") ||
    resolved.startsWith("packages/")
  ) {
    return `Conversation engine must not import Radioso product implementation code: ${record.filePath} -> ${record.specifier}`;
  }

  return null;
};

const validateCensusImport = (record) => {
  const filePath = normalizePath(record.filePath);
  if (!filePath.startsWith("packages/census/")) {
    return null;
  }
  // The rule guards the SHIPPED library (src/). Test files and build tooling are not part of the
  // published graph and legitimately import dev tooling such as vitest. The runtime guarantee they
  // exist to protect is enforced separately, and more strictly, by the entry-point import budget in
  // packages/census/tests/entryPoints.test.ts, which traces what the built dist actually loads.
  if (/^packages\/census\/(tests\/|[^/]+\.config\.ts$)/.test(filePath)) {
    return null;
  }

  const specifier = record.specifier;
  const isBare = !specifier.startsWith(".") && !specifier.startsWith("/");
  if (isBare) {
    if (specifier.startsWith("node:")) {
      return null;
    }
    return `Census must have zero runtime dependencies and can only import Node built-ins or its own relative modules: ${record.filePath} -> ${record.specifier}`;
  }

  const resolved = resolveImportPath(record.filePath, record.specifier);
  if (!resolved || !resolved.startsWith("packages/census/")) {
    return `Census must have zero runtime dependencies and can only import Node built-ins or its own relative modules: ${record.filePath} -> ${record.specifier}`;
  }

  return null;
};

const collectImportRecords = async (root) => {
  const files = await listSourceFiles(root);
  const records = [];
  for (const filePath of files) {
    const relativePath = normalizePath(path.relative(root, filePath));
    const source = await fs.readFile(filePath, "utf8");
    if (source.includes(generatedRouteMarker)) {
      continue;
    }
    for (const specifier of extractImportSpecifiers(source)) {
      records.push({ filePath: relativePath, specifier });
    }
  }
  return records;
};

const listSourceFiles = async (root) => {
  const files = [];
  for (const sourceRoot of ossSourceRoots) {
    await collectFiles(path.join(root, sourceRoot), files);
  }
  return files;
};

const collectFiles = async (directory, files) => {
  let entries;
  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") {
      return;
    }
    throw error;
  }

  for (const entry of entries) {
    const filePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === ".next" || entry.name === "dist") {
        continue;
      }
      await collectFiles(filePath, files);
      continue;
    }
    if (sourceExtensions.has(path.extname(entry.name))) {
      files.push(filePath);
    }
  }
};

const extractImportSpecifiers = (source) => {
  const specifiers = [];
  for (const match of source.matchAll(importPattern)) {
    specifiers.push(match[1] ?? match[2] ?? match[3]);
  }
  return specifiers;
};

const isOssSourcePath = (filePath) => {
  const normalized = normalizePath(filePath);
  return ossSourceRoots.some((root) => normalized === root || normalized.startsWith(`${root}/`));
};

const isEnterpriseSpecifier = (specifier) =>
  specifier.startsWith("@radioso/enterprise-") ||
  specifier.startsWith("ee/") ||
  specifier.includes("/ee/") ||
  specifier.startsWith("../ee/") ||
  specifier.startsWith("../../ee/") ||
  specifier.startsWith("../../../ee/");

const resolveImportPath = (filePath, specifier) => {
  if (!specifier.startsWith(".")) {
    return null;
  }
  const resolved = normalizePath(path.normalize(path.join(path.dirname(filePath), specifier)));
  return resolved
    .replace(/\.(js|ts|tsx|mjs|cjs)$/, "")
    .replace(/\/index$/, "/index");
};

const normalizePath = (value) => value.split(path.sep).join("/");

const isDirectRun = process.argv[1]
  ? import.meta.url === new URL(process.argv[1], "file:").href
  : false;

if (isDirectRun) {
  const result = await validateRepositoryBoundaries(repoRoot);
  if (!result.valid) {
    process.stderr.write(`Architecture boundary validation failed:\n${result.errors.join("\n")}\n`);
    process.exit(1);
  }
  process.stdout.write("Architecture boundary validation passed.\n");
}
