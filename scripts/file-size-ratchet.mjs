#!/usr/bin/env node
/**
 * File-size ratchet.
 *
 * AGENTS.md prefers small, named modules. A plain pass/fail gate at 1,000 lines would fail the
 * build for every file already past the limit, which blocks unrelated work rather than stopping
 * new growth. This wraps the limit in two rules instead:
 *
 *   1. A file over the limit that is not in file-size-baseline.json fails the build. Split it
 *      before it lands, rather than grandfathering it in by writing to the file first.
 *   2. A baselined file that grows past its recorded line count also fails. The baseline is a
 *      ceiling on the files that are already too big, not a free pass to keep growing them.
 *
 * The baseline only ever shrinks. `--update` re-records it, and a baseline entry that no
 * longer matches reality (the file shrank, dropped under the limit, or disappeared) fails the
 * build, so a stale entry cannot sit there exempting line counts the file no longer has.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, extname, join, resolve } from 'node:path'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const BASELINE_PATH = join(ROOT, 'file-size-baseline.json')

/** The line limit this ratchet enforces. Counted like `wc -l`: newline characters, so a final
 *  line with no trailing newline is not counted — exactly what `wc -l` does. */
export const LINE_LIMIT = 1000

/** Extensions considered production source. `.d.ts` files fall under `.ts` here (`extname`
 *  returns `.ts` for them), which is what keeps a few packages that ship their public contract
 *  as hand-written declaration files with no `.ts` counterpart at all (packages/connector-api,
 *  packages/skill-contract, packages/usage-contract) — and packages/conversation-contract's
 *  2,000+ line index.d.ts — inside the gate. Generated `.d.ts` is excluded below by the same
 *  header-marker check as any other generated file. */
const SOURCE_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.mjs', '.cjs'])

const hasSourceExtension = (relativePath) => SOURCE_EXTENSIONS.has(extname(relativePath))

/** Path-shaped exclusions, kept explicit so the scope rules read here rather than being
 *  scattered across regexes. */
const EXCLUDED_PATH_PATTERNS = [
  // Never tracked, but defensive: a pathspec under a package root with no `src/` (see
  // scopeRoots below) would otherwise walk into it.
  { name: 'node_modules', pattern: /(^|\/)node_modules(\/|$)/ },
  // Tests are a different ratchet's job; this one is about production module size.
  { name: 'test directories', pattern: /(^|\/)(tests|__tests__|e2e)(\/|$)/ },
  { name: 'test/spec filenames', pattern: /\.(test|spec)\.[^/]+$/ },
  // Committed codegen output: typescript-sdk/src/generated, packages/radioso-mcp-server/src/
  // generated, packages/conversation-defaults/src/generated, packages/product-docs/src/
  // generated. Nobody hand-edits these, so their size is not a design signal.
  { name: 'generated directories', pattern: /(^|\/)generated(\/|$)/ },
]

const isExcludedByPath = (relativePath) =>
  EXCLUDED_PATH_PATTERNS.some(({ pattern }) => pattern.test(relativePath))

/** Marker-based exclusion for generated files that do not live under a `generated/` dir — for
 *  example backend/src/shared/infra/kysely/schema.ts, which kysely-codegen regenerates from the
 *  live schema and headers with "This file was generated by kysely-codegen. Please do not edit
 *  it manually." Checked against the same content already read for the line count, so this
 *  costs no extra I/O.
 *
 *  Matches explicit codegen disclaimers only, not prose that happens to contain "generated by"
 *  or "do not edit" (e.g. "Turn ids are generated by Postgres", "Do not edit the order below
 *  without updating X") — both of those are hand-written and must stay in scope. */
const GENERATED_HEADER_PATTERN = /@generated\b|\bthis file (?:was|is) (?:auto-)?generated\b|\bcode generated by\b.*\bdo not edit\b/i

export const isGeneratedByHeader = (content) => {
  const head = content.split('\n', 10).join('\n')
  return GENERATED_HEADER_PATTERN.test(head)
}

/** `wc -l` counts newline characters, not "lines" in the everyday sense: a file whose last
 *  line has no trailing newline does not count that line. Matched here on purpose, so the
 *  number this script prints is the same one `wc -l <file>` would print. */
export const countLines = (content) => {
  let count = 0
  for (let i = 0; i < content.length; i += 1) if (content[i] === '\n') count += 1
  return count
}

const toPosix = (value) => value.split('\\').join('/')

/** Packages that keep their source directly at the package root instead of under `src/`
 *  (packages/connector-api, packages/conversation-contract, packages/document-parser,
 *  packages/skill-contract, packages/usage-contract) still need a scope root. Discovering this
 *  per package, instead of hard-coding the five names, means a future package added either way
 *  is picked up without touching this file. */
const discoverPackageRoots = (relativeBaseDir) => {
  const absoluteBase = join(ROOT, relativeBaseDir)
  if (!existsSync(absoluteBase)) return []
  return readdirSync(absoluteBase, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const packageRelative = toPosix(join(relativeBaseDir, entry.name))
      const srcRelative = `${packageRelative}/src`
      return existsSync(join(ROOT, srcRelative)) ? srcRelative : packageRelative
    })
}

/** The directories this ratchet scopes to. Everything else in the repo (scripts, tests,
 *  infra, docs, docs-portal, ee/packages feature manifests, etc.) is out of scope by omission
 *  rather than by exclusion rule. */
export const buildScopeRoots = () => [
  'backend/src',
  'frontend/app',
  'frontend/components',
  'frontend/hooks',
  'frontend/lib',
  'typescript-sdk/src',
  ...discoverPackageRoots('packages'),
  ...discoverPackageRoots('ee/packages'),
]

const listGitFiles = (roots) => {
  if (roots.length === 0) return []
  const output = execFileSync('git', ['ls-files', '--', ...roots], { cwd: ROOT, encoding: 'utf8' })
  return output.split('\n').filter(Boolean)
}

/** Walks the scope roots and returns `{ relativePath: lineCount }` for every in-scope,
 *  non-excluded, non-generated production file. The only impure piece of this module — kept
 *  separate from evaluateFileSizes/planBaselineUpdate so those stay testable on plain data. */
export const collectFileCounts = () => {
  const candidates = listGitFiles(buildScopeRoots())
  const counts = {}
  for (const relativePath of candidates) {
    if (isExcludedByPath(relativePath)) continue
    if (!hasSourceExtension(relativePath)) continue
    let content
    try {
      content = readFileSync(join(ROOT, relativePath), 'utf8')
    } catch {
      // Listed by git but gone from the working tree (e.g. deleted-but-unstaged); nothing to count.
      continue
    }
    if (isGeneratedByHeader(content)) continue
    counts[relativePath] = countLines(content)
  }
  return counts
}

/**
 * @typedef {Object} FileSizeViolation
 * @property {'new-over-limit'|'grew'|'stale'} type
 * @property {string} file
 * @property {number|null} lines - current line count, or null when the file no longer exists
 * @property {number} limit
 * @property {number} [baselineLines] - the recorded baseline count, present for 'grew' and 'stale'
 * @property {'shrank'|'dropped-below-limit'|'removed'} [reason] - only present when type is 'stale'
 */

/**
 * The pure decision logic. Takes plain data — no filesystem, no git — so it is trivial to test.
 *
 * @param {{ counts: Record<string, number>, baseline: Record<string, number>, limit?: number }} args
 * @returns {FileSizeViolation[]}
 */
export const evaluateFileSizes = ({ counts, baseline, limit = LINE_LIMIT }) => {
  const violations = []

  for (const [file, lines] of Object.entries(counts)) {
    if (lines <= limit) continue
    const recorded = baseline[file]
    if (recorded === undefined) {
      violations.push({ type: 'new-over-limit', file, lines, limit })
    } else if (lines > recorded) {
      violations.push({ type: 'grew', file, lines, limit, baselineLines: recorded })
    } else if (lines < recorded) {
      violations.push({ type: 'stale', file, lines, limit, baselineLines: recorded, reason: 'shrank' })
    }
    // lines === recorded: exactly what the baseline says. No violation.
  }

  for (const [file, recorded] of Object.entries(baseline)) {
    const lines = counts[file]
    if (lines === undefined) {
      violations.push({ type: 'stale', file, lines: null, limit, baselineLines: recorded, reason: 'removed' })
    } else if (lines <= limit) {
      violations.push({ type: 'stale', file, lines, limit, baselineLines: recorded, reason: 'dropped-below-limit' })
    }
    // lines > limit was already handled (or cleared) in the loop above.
  }

  return violations
}

/**
 * @typedef {Object} BaselineUpdatePlan
 * @property {Record<string, number>} baseline - the baseline --update would write
 * @property {{file: string, lines: number}[]} added - newly over-limit files with no prior entry
 * @property {{file: string, from: number, to: number}[]} raised - entries whose count went up
 * @property {{file: string, from: number, to: number}[]} lowered - entries whose count went down
 * @property {{file: string, from: number}[]} removed - entries dropped (shrank under the limit or gone)
 * @property {boolean} blocked - true when added/raised is non-empty and growth was not allowed
 */

/**
 * Decides what `--update` would write, without writing anything. Adding a new entry or raising
 * an existing one is growth and is blocked unless `allowGrowth` is set; lowering or removing an
 * entry is always allowed, because it can only tighten the ceiling.
 *
 * @param {{ counts: Record<string, number>, baseline: Record<string, number>, allowGrowth?: boolean }} args
 * @returns {BaselineUpdatePlan}
 */
export const planBaselineUpdate = ({ counts, baseline, allowGrowth = false }) => {
  const nextBaseline = {}
  const added = []
  const raised = []
  const lowered = []
  const removed = []

  for (const [file, lines] of Object.entries(counts)) {
    if (lines <= LINE_LIMIT) continue
    const previous = baseline[file]
    if (previous === undefined) {
      added.push({ file, lines })
    } else if (lines > previous) {
      raised.push({ file, from: previous, to: lines })
    } else if (lines < previous) {
      lowered.push({ file, from: previous, to: lines })
    }
    nextBaseline[file] = lines
  }

  for (const [file, recorded] of Object.entries(baseline)) {
    if (!(file in nextBaseline)) removed.push({ file, from: recorded })
  }

  return {
    baseline: nextBaseline,
    added,
    raised,
    lowered,
    removed,
    blocked: !allowGrowth && (added.length > 0 || raised.length > 0),
  }
}

const sortKeys = (record) =>
  Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)))

const runUpdate = ({ counts, baseline, allowGrowth }) => {
  const plan = planBaselineUpdate({ counts, baseline, allowGrowth })

  if (plan.blocked) {
    console.error('file-size-ratchet: --update would grow the baseline; pass --allow-growth if that is intended.\n')
    plan.added.forEach((c) => console.error(`  new:   ${c.file}  (${c.lines} lines)`))
    plan.raised.forEach((c) => console.error(`  raise: ${c.file}  ${c.from} -> ${c.to} lines`))
    console.error('\n--update only records a shrink by default, so growth cannot be banked into the baseline by accident.\n')
    process.exit(1)
  }

  writeFileSync(BASELINE_PATH, `${JSON.stringify(sortKeys(plan.baseline), null, 2)}\n`)

  const changeLines = [
    ...plan.added.map((c) => `  new:     ${c.file}  (${c.lines} lines)`),
    ...plan.raised.map((c) => `  raised:  ${c.file}  ${c.from} -> ${c.to} lines`),
    ...plan.lowered.map((c) => `  lowered: ${c.file}  ${c.from} -> ${c.to} lines`),
    ...plan.removed.map((c) => `  removed: ${c.file}  (was ${c.from} lines)`),
  ]

  const fileCount = Object.keys(plan.baseline).length
  if (changeLines.length === 0) {
    console.log(`file-size-ratchet: baseline already matches current state (${fileCount} file(s)).`)
  } else {
    console.log(`file-size-ratchet: recorded ${fileCount} file(s) in file-size-baseline.json:\n`)
    changeLines.forEach((line) => console.log(line))
  }
  process.exit(0)
}

const describe = (violation) => {
  if (violation.type === 'new-over-limit') {
    return `  ${violation.file}  (${violation.lines} lines, limit ${violation.limit})`
  }
  if (violation.type === 'grew') {
    return `  ${violation.file}  ${violation.baselineLines} -> ${violation.lines} lines (limit ${violation.limit})`
  }
  if (violation.reason === 'removed') {
    return `  ${violation.file}  (baselined at ${violation.baselineLines} lines, file no longer exists)`
  }
  if (violation.reason === 'dropped-below-limit') {
    return `  ${violation.file}  ${violation.baselineLines} -> ${violation.lines} lines (now under the limit of ${violation.limit})`
  }
  return `  ${violation.file}  ${violation.baselineLines} -> ${violation.lines} lines`
}

const runCheck = ({ counts, baseline }) => {
  const violations = evaluateFileSizes({ counts, baseline, limit: LINE_LIMIT })
  const newOverLimit = violations.filter((v) => v.type === 'new-over-limit')
  const grew = violations.filter((v) => v.type === 'grew')
  const stale = violations.filter((v) => v.type === 'stale')

  if (newOverLimit.length) {
    console.error(`file-size-ratchet: ${newOverLimit.length} file(s) over ${LINE_LIMIT} lines with no baseline entry:\n`)
    newOverLimit.forEach((v) => console.error(describe(v)))
    console.error('\nSplit it before it lands. If it must land as-is, that still needs a baseline entry; see\n`pnpm run lint:file-size:baseline` (or the --update flag on this script) with --allow-growth.\n')
  }

  if (grew.length) {
    console.error(`file-size-ratchet: ${grew.length} baselined file(s) grew past their recorded line count:\n`)
    grew.forEach((v) => console.error(describe(v)))
    console.error('\nThe baseline is a ceiling, not a budget. Split the file back down, or shrink something else in it.\n')
  }

  if (stale.length) {
    console.error(`file-size-ratchet: ${stale.length} baseline entry(ies) no longer match reality:\n`)
    stale.forEach((v) => console.error(describe(v)))
    console.error('\nfile-size-baseline.json must match the current line counts exactly, the same way knip-baseline.json\ndoes. Re-record with --update.\n')
  }

  if (!violations.length) {
    console.log(`file-size-ratchet: clean (${Object.keys(baseline).length} file(s) baselined, all matching, nothing new over ${LINE_LIMIT} lines).`)
  }

  process.exit(violations.length ? 1 : 0)
}

const isDirectRun = process.argv[1]
  ? import.meta.url === new URL(process.argv[1], 'file:').href
  : false

if (isDirectRun) {
  const args = process.argv.slice(2)
  const shouldUpdate = args.includes('--update')
  const allowGrowth = args.includes('--allow-growth')

  const baseline = existsSync(BASELINE_PATH) ? JSON.parse(readFileSync(BASELINE_PATH, 'utf8')) : {}
  const counts = collectFileCounts()

  if (shouldUpdate) {
    runUpdate({ counts, baseline, allowGrowth })
  } else {
    runCheck({ counts, baseline })
  }
}
