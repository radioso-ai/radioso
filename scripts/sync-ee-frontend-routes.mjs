#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  collectFrontendAgentCreationActionContributions,
  collectFrontendComponentContributions,
  collectFrontendRouteContributions,
  collectGeneratedDirectories,
  loadEnterpriseFeatureManifests,
  validateFeatureManifests,
} from "./enterprise-feature-manifests.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const frontendRoot = path.join(repoRoot, "frontend");
const marker = "// Generated by scripts/sync-ee-frontend-routes.mjs. Do not edit.\n";
const componentStubMarker = "// Stub generated when Enterprise Edition is disabled. Do not edit.\n";
const agentCreationActionsConfigPath = "public/enterprise-agent-creation-actions.json";

export const buildGeneratedRouteFiles = (routes) => routes.map((route) => ({
  relativePath: route.relativePath,
  content: buildRouteContent(route),
}));

export const buildGeneratedComponentFiles = (components) => components.map((component) => ({
  relativePath: component.relativePath,
  content: buildRouteContent(component),
}));

const buildComponentStubContent = (component) => {
  const lines = [
    componentStubMarker.trimEnd(),
    "",
  ];
  for (const exportName of component.exports) {
    if (exportName === "default") {
      lines.push("const stub: unknown = null");
      lines.push("export default stub");
    } else {
      lines.push(`export const ${exportName}: unknown = null`);
    }
  }
  lines.push("");
  return lines.join("\n");
};

export const buildAgentCreationActionsConfig = (actions) => `${JSON.stringify({ actions }, null, 2)}\n`;

const buildRouteContent = (route) => {
  const moduleSpecifier = `${route.packageName}/${route.exportPath}`;
  const lines = [];
  if (route.runtime) {
    lines.push(`export const runtime = '${route.runtime}'`);
  }
  if (route.dynamic) {
    lines.push(`export const dynamic = '${route.dynamic}'`);
  }
  if (lines.length > 0) {
    lines.push("");
  }

  if (route.exports.length === 1 && route.exports[0] === "default") {
    lines.push(`export { default } from '${moduleSpecifier}'`);
    lines.push("");
    return lines.join("\n");
  }

  lines.push("export {");
  for (const exportName of route.exports) {
    if (exportName === "default") {
      lines.push("  default,");
    } else {
      lines.push(`  ${exportName},`);
    }
  }
  lines.push(`} from '${moduleSpecifier}'`);
  lines.push("");
  return lines.join("\n");
};

const writeIfChanged = async (filePath, content) => {
  try {
    const current = await fs.readFile(filePath, "utf8");
    if (current === content) {
      return;
    }
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }

  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content);
};

export const enableEnterpriseFrontendRoutes = async (options = {}) => {
  const resolvedFrontendRoot = options.frontendRoot ?? frontendRoot;
  let manifests = options.manifests;
  const getManifests = async () => {
    manifests ??= await loadValidatedManifests();
    return manifests;
  };
  const routes = options.routes ?? collectFrontendRouteContributions(await getManifests());
  const components = options.components ?? collectFrontendComponentContributions(await getManifests());
  const agentCreationActions = options.agentCreationActions ?? collectFrontendAgentCreationActionContributions(await getManifests());
  for (const file of buildGeneratedRouteFiles(routes)) {
    await writeIfChanged(path.join(resolvedFrontendRoot, file.relativePath), `${marker}${file.content}`);
  }
  for (const filePath of await findMarkedGeneratedFiles(path.join(resolvedFrontendRoot, "lib"), [marker, componentStubMarker])) {
    await fs.rm(filePath, { force: true });
  }
  for (const file of buildGeneratedComponentFiles(components)) {
    await writeIfChanged(path.join(resolvedFrontendRoot, file.relativePath), `${marker}${file.content}`);
  }
  await writeIfChanged(
    path.join(resolvedFrontendRoot, agentCreationActionsConfigPath),
    buildAgentCreationActionsConfig(agentCreationActions),
  );
};

export const disableEnterpriseFrontendRoutes = async (options = {}) => {
  const resolvedFrontendRoot = options.frontendRoot ?? frontendRoot;
  const routes = options.routes ?? await loadRoutesForCleanup();
  const components = options.components ?? await loadComponentsForCleanup();
  for (const file of buildGeneratedRouteFiles(routes)) {
    await fs.rm(path.join(resolvedFrontendRoot, file.relativePath), { force: true });
  }
  for (const filePath of await findMarkedGeneratedFiles(path.join(resolvedFrontendRoot, "app"))) {
    await fs.rm(filePath, { force: true });
  }
  for (const filePath of await findMarkedGeneratedFiles(path.join(resolvedFrontendRoot, "lib"), [marker, componentStubMarker])) {
    await fs.rm(filePath, { force: true });
  }
  // Replace EE component wrappers with stubs so OSS builds resolve imports.
  for (const component of components) {
    await writeIfChanged(
      path.join(resolvedFrontendRoot, component.relativePath),
      buildComponentStubContent(component),
    );
  }

  for (const directory of collectGeneratedDirectories(routes)) {
    await fs.rm(path.join(resolvedFrontendRoot, directory), { recursive: true, force: true });
  }
  await fs.rm(path.join(resolvedFrontendRoot, agentCreationActionsConfigPath), { force: true });
};

const loadRoutesForCleanup = async () => {
  try {
    return await loadValidatedRoutes();
  } catch {
    return [];
  }
};

const loadValidatedRoutes = async () => {
  const manifests = await loadValidatedManifests();
  return collectFrontendRouteContributions(manifests);
};

const loadComponentsForCleanup = async () => {
  try {
    const manifests = await loadValidatedManifests();
    return collectFrontendComponentContributions(manifests);
  } catch {
    return [];
  }
};

const loadValidatedManifests = async () => {
  const manifests = await loadEnterpriseFeatureManifests();
  const validation = await validateFeatureManifests(manifests);
  if (!validation.valid) {
    throw new Error(`Invalid Enterprise feature manifests:\n${validation.errors.join("\n")}`);
  }
  return manifests;
};

const findMarkedGeneratedFiles = async (directory, prefixes = [marker]) => {
  const files = [];
  let entries;
  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") {
      return files;
    }
    throw error;
  }

  for (const entry of entries) {
    const filePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...await findMarkedGeneratedFiles(filePath, prefixes));
      continue;
    }
    const content = await fs.readFile(filePath, "utf8");
    if (prefixes.some((prefix) => content.startsWith(prefix))) {
      files.push(filePath);
    }
  }
  return files;
};

const command = process.argv[2];

const isDirectRun = process.argv[1]
  ? import.meta.url === new URL(process.argv[1], "file:").href
  : false;

if (isDirectRun) {
  if (command === "enable") {
    await enableEnterpriseFrontendRoutes();
  } else if (command === "disable") {
    await disableEnterpriseFrontendRoutes();
  } else {
    process.stderr.write("Usage: node scripts/sync-ee-frontend-routes.mjs <enable|disable>\n");
    process.exit(1);
  }
}
