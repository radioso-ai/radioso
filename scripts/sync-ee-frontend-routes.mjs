#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const frontendRoot = path.join(repoRoot, "frontend");
const marker = "// Generated by scripts/sync-ee-frontend-routes.mjs. Do not edit.\n";

const generatedFiles = [
  {
    relativePath: "app/embed/[token]/page.tsx",
    content: "export { default } from '@radioso/enterprise-embed-widget/embed-page'\n",
  },
  {
    relativePath: "app/embed/[token]/layout.tsx",
    content: "export { default, metadata } from '@radioso/enterprise-embed-widget/embed-layout'\n",
  },
  {
    relativePath: "app/api/embed/session/[token]/route.ts",
    content: [
      "export const runtime = 'nodejs'",
      "export const dynamic = 'force-dynamic'",
      "",
      "export {",
      "  OPTIONS,",
      "  POST,",
      "} from '@radioso/enterprise-embed-widget/routes/embed-session'",
      "",
    ].join("\n"),
  },
  {
    relativePath: "app/radioso-embed.js/route.ts",
    content: [
      "export const runtime = 'nodejs'",
      "export const dynamic = 'force-static'",
      "",
      "export {",
      "  GET,",
      "} from '@radioso/enterprise-embed-widget/routes/radioso-embed-script'",
      "",
    ].join("\n"),
  },
];

const generatedDirectories = [
  "app/embed",
  "app/api/embed",
  "app/radioso-embed.js",
];

const writeIfChanged = async (filePath, content) => {
  try {
    const current = await fs.readFile(filePath, "utf8");
    if (current === content) {
      return;
    }
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }

  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content);
};

const enable = async () => {
  for (const file of generatedFiles) {
    await writeIfChanged(path.join(frontendRoot, file.relativePath), `${marker}${file.content}`);
  }
};

const disable = async () => {
  for (const file of generatedFiles) {
    await fs.rm(path.join(frontendRoot, file.relativePath), { force: true });
  }

  for (const directory of generatedDirectories) {
    await fs.rm(path.join(frontendRoot, directory), { recursive: true, force: true });
  }
};

const command = process.argv[2];

if (command === "enable") {
  await enable();
} else if (command === "disable") {
  await disable();
} else {
  process.stderr.write("Usage: node scripts/sync-ee-frontend-routes.mjs <enable|disable>\n");
  process.exit(1);
}
